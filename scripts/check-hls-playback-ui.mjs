import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from 'playwright-core';

const base = process.env.VISUAL_BASE_URL || 'http://127.0.0.1:3107';
const directory = process.env.HLS_FIXTURE_DIR;
if (!directory) throw new Error('Set HLS_FIXTURE_DIR to a package generated by media:prepare-hls (at least 12 seconds, multiple levels).');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const grants = [], requests = [], events = [], errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.addInitScript(() => {
    if (navigator.connection) Object.defineProperties(navigator.connection, {
      downlink: { get: () => 10 }, effectiveType: { get: () => '4g' }, saveData: { get: () => false },
    });
  });
  await page.route('**/api/**', route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname;
    if (!path.startsWith('/api/')) return route.continue();
    let data = {};
    if (path.endsWith('/auth/session')) data = { userId: 'hls-check', name: 'HLS Check' };
    else if (path.includes('/series/')) data = { id: 'hls-check', slug: 'hls-check', title: 'HLS playback check',
      episodeCount: 2, freeEpisodeCount: 2, price: 0, genres: [], cast: [],
      episodes: [1, 2].map(episodeNo => ({ id: `episode-${episodeNo}`, episodeNo, title: 'Episode', duration: '0:12', isFree: true })) };
    else if (path.endsWith('/playback')) {
      const episodeNo = Number(url.searchParams.get('episodeNo'));
      const source = `${base}/hls-check/episode${episodeNo}-grant${grants.length + 1}/master.m3u8`;
      grants.push({ episodeNo, source, session: url.searchParams.get('sessionId'), prewarm: url.searchParams.get('prewarm') });
      data = { authorized: true, delivery: 'hls', signedUrl: source, trackingToken: 'test',
        expiresAt: new Date(Date.now() + 600000).toISOString(), resumePositionSeconds: 0,
        prefetchUrls: ['master.m3u8', 'v360/index.m3u8', 'v360/init.mp4', 'v360/seg-000000.m4s'].map(file => new URL(file, source).href) };
    } else if (path.endsWith('/me/watch-history') && request.method() === 'POST') events.push(request.postDataJSON());
    return route.fulfill({ json: { data } });
  });
  await page.route('**/hls-check/**', route => {
    const url = new URL(route.request().url());
    const match = /^\/hls-check\/([^/]+)\/(.+)$/.exec(url.pathname);
    if (!match) return route.continue();
    const file = match[2];
    assert.match(file, /^(master\.m3u8|v(?:360|480|720|1080)\/(index\.m3u8|init\.mp4|seg-\d{6}\.m4s))$/);
    requests.push({ url: url.href, grant: match[1], file });
    const body = readFileSync(join(directory, file));
    return route.fulfill({ status: 200, contentType: file.endsWith('.m3u8') ? 'application/vnd.apple.mpegurl' : 'video/mp4',
      headers: { 'content-length': String(body.length) }, body });
  });
  await page.goto(`${base}/terms`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForFunction(() => document.querySelector('#__nuxt')?.__vue_app__?.config.globalProperties.$router);
  await page.evaluate(() => document.querySelector('#__nuxt').__vue_app__.config.globalProperties.$router.push('/watch/hls-check/1'));
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForFunction(() => { const video = document.querySelector('video'); return video?.currentTime > 1 && !video.paused; });
  assert.equal(requests.find(r => r.file.endsWith('.m4s'))?.file, 'v360/seg-000000.m4s', 'first segment starts at lowest bitrate');
  assert.match(await page.getByRole('button', { name: 'Video quality', exact: true }).innerText(), /Auto/);
  await page.waitForFunction(() => document.querySelector('video')?.currentTime > 5.5);
  assert.ok(requests.some(r => /^v(?:480|720|1080)\/seg-/.test(r.file)), 'ABR should upgrade on a fast connection');
  const warm = grants.find(g => g.episodeNo === 2);
  assert.ok(warm, 'next episode grant should be prefetched');
  assert.equal(warm.prewarm, 'true');
  assert.notEqual(warm.session, grants[0].session);
  assert.equal(events.some(event => event.episodeNo === 2), false, 'preloading must not record playback');
  await page.getByRole('button', { name: 'Next episode', exact: true }).click();
  await page.waitForURL('**/watch/hls-check/2');
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('video')?.currentTime > 1);
  assert.equal(grants.filter(g => g.episodeNo === 2).length, 1, 'switching episodes reuses the prefetched authorization');
  await page.locator('video').evaluate(video => video.pause());
  await page.getByRole('slider', { name: 'Seek', exact: true }).fill('60');
  await page.waitForFunction(() => document.querySelector('video')?.currentTime >= 7);
  assert.deepEqual(errors, []);
  console.log('HLS browser checks passed: real fMP4 decoding, low-bitrate start, automatic upgrade, next episode warming and session handoff, seek.');
} catch (error) {
  console.error({ url: page.url(), errors, grants, requests }); throw error;
} finally { await browser.close(); }
